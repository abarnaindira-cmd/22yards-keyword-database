import os
import openpyxl
import sys
sys.stdout.reconfigure(encoding='utf-8')

from sqlalchemy import text
from app.database import SessionLocal
from app.models.product import Product
from app.models.competitor import CompetitorProduct
from app.services.title_generator import fallback_generate_title
from app.services.excel_exporter import export_final_product_data_to_excel

def audit_pilot():
    db = SessionLocal()

    # Re-select the exact 100 pilot products
    comp_sql = """
    SELECT source_product_asin, COUNT(DISTINCT competitor_title) AS comp_count
    FROM competitor_products
    WHERE competitor_title IS NOT NULL AND TRIM(competitor_title) != ''
    GROUP BY source_product_asin;
    """
    comp_counts = db.execute(text(comp_sql)).fetchall()
    asin_to_comp = {row[0]: row[1] for row in comp_counts}

    all_prods = db.query(Product).order_by(Product.id.asc()).all()

    prods_20_plus = [p for p in all_prods if asin_to_comp.get(p.asin, 0) >= 20]
    prods_1_to_19 = [p for p in all_prods if 1 <= asin_to_comp.get(p.asin, 0) < 20]

    pilot_prods = prods_20_plus[:70] + prods_1_to_19[:30]
    pilot_asins = [p.asin for p in pilot_prods]

    print("==========================================================================")
    print("CONTROLLED 100-PRODUCT PILOT AUDIT REPORT")
    print("==========================================================================")

    fpd_rows = db.execute(
        text("SELECT sku_id, product_name, final_product_title, all_keywords FROM final_product_data WHERE sku_id IN :asins"),
        {"asins": tuple(pilot_asins)}
    ).fetchall()

    fpd_map = {r[0]: r for r in fpd_rows}

    groq_success_count = 0
    fallback_count = 0
    failed_count = 0

    groq_20_plus = 0
    groq_1_to_19 = 0
    fb_20_plus = 0
    fb_1_to_19 = 0

    for p in pilot_prods:
        c_count = asin_to_comp.get(p.asin, 0)
        rec = fpd_map.get(p.asin)
        if not rec:
            failed_count += 1
        else:
            sku_id, p_name, final_title, kws_json = rec[0], rec[1], rec[2], rec[3]
            import json
            kws = json.loads(kws_json) if isinstance(kws_json, str) else (kws_json or [])
            expected_fb = fallback_generate_title(p_name, kws)

            if final_title == expected_fb:
                fallback_count += 1
                if c_count >= 20:
                    fb_20_plus += 1
                else:
                    fb_1_to_19 += 1
            else:
                groq_success_count += 1
                if c_count >= 20:
                    groq_20_plus += 1
                else:
                    groq_1_to_19 += 1

    print("\n[SECTION 1: PILOT METRICS & EXECUTION BREAKDOWN]")
    print(f"  - Total Selected Pilot Products          : {len(pilot_prods)}")
    print(f"  - Successfully Generated by Groq AI      : {groq_success_count} ({groq_success_count/100*100:.1f}%)")
    print(f"    * Products with >=20 titles (Groq AI)  : {groq_20_plus}/70")
    print(f"    * Products with 1-19 titles (Groq AI)  : {groq_1_to_19}/30")
    print(f"  - Fallback-Generated Titles              : {fallback_count}")
    print(f"    * Products with >=20 titles (Fallback) : {fb_20_plus}/70")
    print(f"    * Products with 1-19 titles (Fallback) : {fb_1_to_19}/30")
    print(f"  - Failed Titles                          : {failed_count}")
    print(f"  - Total MySQL Database Records Updated  : {len(fpd_rows)}/100")

    # Step 2: Export & Verify Excel Export File
    export_filepath = export_final_product_data_to_excel(
        db,
        asins_list=pilot_asins,
        output_filepath=os.path.join("scratch", "Final_Product_Data_Pilot_100_Audited.xlsx")
    )

    wb = openpyxl.load_workbook(export_filepath)
    sheet = wb.active
    total_excel_rows = sheet.max_row
    total_excel_cols = sheet.max_column
    headers = [sheet.cell(row=1, column=c).value for c in range(1, total_excel_cols + 1)]

    exported_skus = [sheet.cell(row=r, column=2).value for r in range(2, total_excel_rows + 1) if sheet.cell(row=r, column=2).value]

    selected_set = set(pilot_asins)
    exported_set = set(exported_skus)

    missing_skus = list(selected_set - exported_set)
    extra_skus = list(exported_set - selected_set)

    import collections
    sku_counts = collections.Counter(exported_skus)
    duplicate_skus = [sku for sku, cnt in sku_counts.items() if cnt > 1]

    print("\n[SECTION 2: PILOT EXCEL EXPORT VERIFICATION]")
    print(f"  - Export File Path                       : {export_filepath}")
    print(f"  - File Size                              : {os.path.getsize(export_filepath)} bytes")
    print(f"  - Total Rows in File                     : {total_excel_rows} (1 Header + 100 Data Rows)")
    print(f"  - Total Columns                          : {total_excel_cols} (Expected: 4)")
    print(f"  - Headers                                : {headers}")
    print(f"  - Header Match Exactly                   : {headers == ['product_name', 'sku_id', 'final_product_title', 'all_keywords']}")
    print(f"  - Missing SKUs                           : {len(missing_skus)}")
    print(f"  - Extra SKUs                             : {len(extra_skus)}")
    print(f"  - Duplicate SKUs                         : {len(duplicate_skus)}")

    row_2_data = [sheet.cell(row=2, column=c).value for c in range(1, 5)]
    print("\n[SECTION 3: SAMPLE DATA ROW (Row 2)]")
    print(f"  - product_name       : {row_2_data[0]}")
    print(f"  - sku_id             : {row_2_data[1]}")
    print(f"  - final_product_title: {row_2_data[2]}")
    print(f"  - all_keywords       : {str(row_2_data[3])[:100]}...")

    db.close()
    print("\n==========================================================================")
    print("PILOT AUDIT REPORT COMPLETED")
    print("==========================================================================")

if __name__ == "__main__":
    audit_pilot()
